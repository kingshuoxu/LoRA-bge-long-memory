def generate(seed: int) -> dict:
    rng = random.Random(seed)
    chains = list(_CHAINS)
    rest = [item for item in _TAUGHT if item not in chains]
    rng.shuffle(rest)
    taught = chains + rest
    never = list(_TRAPS) + list(_WHO_TRAPS) + list(_TYPE_TRAPS)
    extra = list(_NEVER)
    rng.shuffle(extra)
    rng.shuffle(never)
    never.extend(extra[:4])
    if len(_TYPE_TRAPS) < 15:
        raise RuntimeError("种类干扰不足 15 条")
    if len(_CHAINS) < 10:
        raise RuntimeError("短链不足 10 条")
    if len(_FENCE) < 15:
        raise RuntimeError("已知实体的未知属性不足 15 条")
    if len(_SPOUSE_TRAPS) < 8:
        raise RuntimeError("配偶问法不足 8 条")
    if len(_KIN_NESTED) < 8:
        raise RuntimeError("嵌套亲属问法不足 8 条")
    if len(_EITHER) < 10 or len(_SPOKEN_SPOUSE) < 8 or len(_KEEPER_CALLED) < 8 or len(_WHO_MADE) < 8:
        raise RuntimeError("新的陷阱题不够")
    if len(_DAUGHTER_CHAINS) < 8 or len(_SALT_TOWERS) < 8 or len(_GUARD_NOT_MAKE) < 8:
        raise RuntimeError("女儿、盐塔或守塔题不够")
    return {
        "seed": seed,
        "taught": [
            {"q": question, "gold": gold, "hops": 2 if question in _TWO_HOP else 1}
            for question, gold in taught
        ],
        "never": never,
    }
